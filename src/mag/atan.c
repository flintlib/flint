/* an approximation of atan(x) for 0 <= x, within 1e-13 relatively:
   with p = floor(256 t) for t = x or 1/x, atan(t) = atan(p/256) +
   atan(u), u = (256 t - p) / (p t + 256) < 1/256, by the series to u^5
   (the omitted term below u^7 / 7 < 2^-58); the double arithmetic adds a
   few units of 2^-53 */
static double
mag_atan_d(double x)
{
    double t, u, v;
    int p, flip;

    t = x;
    flip = 0;
    if (t > 1.0)
    {
        t = 1.0 / t;
        flip = 1;
    }

    p = (int) (t * 256.0);
    if (p >= 256)
        p = 255;

    v = atan_tab[p];
    t = (256.0 * t - p) / (p * t + 256.0);

    /* t - t^3/3 + t^5/5 */
    u = t * t;
    t = (t * (1.0 / 15.0)) * (15.0 - 5.0 * u + 3.0 * (u * u));
    v += t;

    if (flip)
        v = 1.5707963267948966192 - v;

    return v;
}

void
mag_atan(mag_t res, const mag_t x)
{
    if (mag_is_zero(x))
    {
        mag_zero(res);
    }
    else if (mag_cmp_2exp_si(x, MAG_BITS) > 0)
    {
        mag_const_pi(res);
        mag_mul_2exp_si(res, res, -1);
    }
    else if (mag_cmp_2exp_si(x, -(MAG_BITS / 2)) < 0)
    {
        mag_set(res, x);
    }
    else
    {
        double t;

        t = ldexp(MAG_MAN(x), MAG_EXP(x) - MAG_BITS);
        t = mag_atan_d(t);
        t = t * (1.0 + 1e-12);

        mag_set_d(res, t);
    }
}

void
mag_atan_lower(mag_t res, const mag_t x)
{
    if (mag_is_zero(x))
    {
        mag_zero(res);
    }
    else if (mag_is_inf(x))
    {
        mag_const_pi_lower(res);
        mag_mul_2exp_si(res, res, -1);
    }
    else if (mag_cmp_2exp_si(x, MAG_BITS) > 0)
    {
        /* atan(x) > pi/2 - 1/x */
        mag_t t;
        mag_init(t);
        mag_one(t);
        mag_div(t, t, x);
        mag_const_pi_lower(res);
        mag_mul_2exp_si(res, res, -1);
        mag_sub_lower(res, res, t);
        mag_clear(t);
    }
    else if (mag_cmp_2exp_si(x, -MAG_BITS) < 0)
    {
        /* atan(x) > x - x^2 */
        mag_t t;
        mag_init(t);
        mag_mul(t, x, x);
        mag_sub_lower(res, x, t);
        mag_clear(t);
    }
    else
    {
        double t;

        t = ldexp(MAG_MAN(x), MAG_EXP(x) - MAG_BITS);
        t = mag_atan_d(t);
        t = t * (1.0 - 1e-12);

        mag_set_d_lower(res, t);
    }
}
