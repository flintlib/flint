/* Sets are tabulated for every size up to 32 and for 40 and 48, so a
   size above 32 is served either by the largest set below it, with
   one followup series per uncovered value, or by padding up to the
   next set.  Which is better depends on how good the followup series
   are, and that differs by kind: a logarithm followup uses
   atanh(1/(2p^2-1)), an argument around 2^30, while a Gaussian one
   uses the quotient between neighbouring primes, an argument around
   2^5, whose series is far slower.  Measured at 10^5 bits (the ratio
   of padding up to going down, so > 1 means going down is better):

       logs     n = 33 .. 39: 1.21, 1.14, 1.12, 1.09, 1.05, 1.02, 1.04
                n = 41 .. 47: 1.14, 1.11, 1.16, 1.11, 1.04, 1.02, 0.97
       angles   n = 33 .. 39: 1.14, 1.08, 1.00, 0.95, 0.90, 0.86, 0.83
                n = 41 .. 47: 1.13, 1.08, 1.02, 0.96, 0.93, 0.89, 0.86

   so the largest set below wins throughout for the logarithms (by up
   to 21%, losing 3% at worst) but only for two or three followups for
   the angles (losing up to 21% beyond that).  Hence the limits below;
   they keep both kinds within about 5% of the better choice.  The
   Lehmer measure is not a usable criterion here: it puts the
   crossover at one followup for both kinds, because it weights an
   argument as 1/log x while under FFT multiplication a binary
   splitting costs about M(prec) per tree level, so halving the terms
   saves a level, not half the work.

   Below the smallest tabulated size the smallest set is used: the
   n = 1, 2, 3 logarithm sets and the n = 2 arctangent set have worse
   Lehmer measures than n = 4 and n = 3 respectively, so they are not
   tabulated at all.  (The measure is not monotone in n either -- the
   7-term logarithm set has mu = 1.49 against 1.41 for the 8-term one
   -- but the exact size wins in practice.) */
#define MP_REAL_MACHIN_MAX_FOLLOWUPS(gaussian) ((gaussian) ? 2 : 8)
const mp_real_machin_struct *
_mp_real_machin_table(int gaussian, slong num)
{
    const mp_real_machin_struct * tab = gaussian ? machin_atan : machin_log;
    slong len = gaussian ? (slong) (sizeof(machin_atan) / sizeof(machin_atan[0]))
                         : (slong) (sizeof(machin_log) / sizeof(machin_log[0]));
    slong i;

    for (i = len - 1; i > 0; i--)
        if (tab[i].num <= num)
        {
            if (num - tab[i].num > MP_REAL_MACHIN_MAX_FOLLOWUPS(gaussian)
                && i + 1 < len)
                return tab + i + 1;
            return tab + i;
        }
    return tab;
}


