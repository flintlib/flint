/* The denominators are written into the table rows below rather than
   named: a static const object is not a constant expression in C, so
   initializing the rows from named denominators is a GNU extension
   that MSVC rejects.

   Arguments are stored as (low, high) 64-bit halves -- two limbs on
   64-bit systems, four on 32-bit -- so any argument below 2^128 is
   plain data. */
#if FLINT_BITS == 64
#define X(lo, hi) UWORD(lo), UWORD(hi)
#else
#define X(lo, hi) (ulong) (lo ## ULL), (ulong) ((lo ## ULL) >> 32), \
                  (ulong) (hi ## ULL), (ulong) ((hi ## ULL) >> 32)
#endif

/* Machin-type sets for the logarithms of the first n primes,

       log p_i = (1/den) sum_j c_ij atanh(1/x_j),

   and for the arguments of the first n nonreal Gaussian primes,

       arg pi_i = (1/den) sum_j c_ij atan(1/x_j),

   with the x_j as large as possible: x^2 - 1 smooth over the primes
   (Luca-Najman's smooth neighbours) in the first case, x^2 + 1 smooth
   over the norms in the second.  Sets are tabulated for every n up to
   32 and for n = 40 and 48; those for up to 24 primes and 22 Gaussian
   primes are arb's (formerly in arb/log_primes.c), the rest come from

       https://github.com/fredrik-johansson/machin

   which also generates new ones and lists the Lehmer measures quoted
   below.  Only the arguments, the denominator and the coefficient bit
   size are stored: the coefficient matrix itself is reconstructed on
   first use (see below), as in rel_tab.c.  The arguments are
   MP_REAL_MACHIN_X_LIMBS limbs each (128 bits). */


