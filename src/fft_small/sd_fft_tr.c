/*
    This module contains the function `sd_fft_trunc_tr`, the transpose of the
    truncated FFT `sd_fft_trunc`, together with the helper functions and macros
    to implement it.

    ********************************************************************************

    `sd_fft_trunc(Q, d, L, itrunc, otrunc)` is a linear map: it reads the
    `itrunc` entries `d[0], ..., d[itrunc-1]`, treats the remaining entries of
    the length `2^L` array as zero, and writes the `otrunc` entries
    `d[0], ..., d[otrunc-1]`. Writing `M` for its matrix, of size
    `otrunc x itrunc`, the function here computes `M^T`, in place: it reads
    `otrunc` entries and writes `itrunc` entries. Equivalently, for all `a` of
    length `itrunc` and all `v` of length `otrunc`,

        <sd_fft_trunc(a), v> == <a, sd_fft_trunc_tr(v)>.

    Note that the parameters `itrunc` and `otrunc` keep the meaning they have
    for `sd_fft_trunc`; in particular `sd_fft_trunc_tr` reads `otrunc` entries
    and writes `itrunc` entries, and not the other way around. This is so that
    a call to `sd_fft_trunc_tr` with given parameters is exactly the transpose
    of the call to `sd_fft_trunc` with the same parameters.

    Since the input of `sd_fft_trunc_tr` lives on the evaluation side, it is
    indexed the same way as the output of `sd_fft_trunc`: the input entry
    corresponding to the point `sd_fft_ctx_w(Q, i)` is at index
    `sd_fft_ctx_trunc_index(L, i)`. The output is indexed as the input of
    `sd_fft_trunc`, i.e. by increasing powers of `x`. Concretely, for
    `0 <= t < itrunc` the output satisfies

        out_data[t] = sum_{0 <= i < otrunc}
                          in_data[sd_fft_ctx_trunc_index(L, i)]
                            * sd_fft_ctx_w(Q, i)^t.

    This invariant is tested in `test/t-sd_fft.c`.

    ********************************************************************************

    A straight-line linear program is transposed by reversing the order of its
    steps and transposing each step (see e.g. [BLS2003]_). Since `sd_fft.c`
    consists of nothing but butterflies, block copies and block zeroings, the
    transposition is entirely mechanical, and this file is `sd_fft.c` read
    backwards:

    - every butterfly is replaced by its transpose. The transpose of the
      decimation-in-time butterfly `(a0, a1) -> (a0 + w*a1, a0 - w*a1)` is the
      decimation-in-frequency butterfly `(a0, a1) -> (a0 + a1, w*(a0 - a1))`,
      i.e. the shape used by `sd_ifft.c`, but with the *forward* twiddle `w`
      instead of `w^-1`. All the twiddle lookups here are therefore identical
      to the ones in `sd_fft.c` (`SET_J_BITS_AND_J_R`, never
      `SET_J_BITS_AND_J_MR`). The butterflies themselves are those of
      `sd_ifft.c` (see butterflies.h): with `W = -w` in place of
      `W = -w^-1`, which they get by multiplying with `nmulmod_fast` and
      `nmulmod`, so that they also have the same bounds;

    - in every sequence of steps, the order is reversed. In the recursion this
      means the row transforms are done before the column transforms, and in
      the basecases it means the layers are traversed from the last to the
      first. In particular, the missing final 4x4 transpose of
      `sd_fft_basecase_4_1` and friends (see `sd_fft_ctx_trunc_index`) becomes
      a missing *initial* 4x4 transpose here, so the two orderings agree;

    - truncation transposes for free. Not reading input `i` means dropping
      column `i` of the matrix, and not writing output `o` means dropping row
      `o`; transposing the resulting submatrix just swaps the two. So the
      truncated butterflies below are generated by the same single macro as in
      `sd_fft.c`, with the loads guarded by `otrunc` and the stores guarded by
      `itrunc`. Unlike the truncated *inverse* butterflies of `sd_ifft.c`,
      no new formula has to be derived.

    The index bookkeeping of the recursion (`n1`, `n2`, `z1`, `z2`, `n1p`,
    `z2p`) is unchanged; only the order of the loops is.

    Consequently `sd_fft_trunc_tr` performs exactly the same number of
    multiplications and additions as `sd_fft_trunc`, and costs the same. Its
    input range, on the other hand, is that of `sd_ifft_trunc`, whose
    butterfly shape it shares (four inputs are summed before any reduction,
    and 8n < 2^53 is the budget; see the analysis of the reverse butterflies
    in mulmod_satisfies_bounds.c): entries in `(-2n, 2n)` are accepted.
    Unlike `sd_ifft_trunc`, whose truncated butterflies can leave that
    range (see the end of mulmod_satisfies_bounds.c), it also produces
    entries in `(-2n, 2n)`: its truncated butterflies keep that range by
    the documented ranges of mulmod_fast and reduce_to_pm1n alone (an
    interval evaluation of each of them under these ranges, and a bound
    propagation through the whole transform at depths up to 16, both
    find no excursion). Like `sd_ifft_trunc` it reads the evaluation side of the
    transform, where the pointwise kernels of `op.c` leave entries in
    `(-3n/2, 3n/2)`.
*/

