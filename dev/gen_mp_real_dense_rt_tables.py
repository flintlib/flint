#!/usr/bin/env python3
"""Emit src/mp_real/dense_rt_tables.c and src/mp_real/dense_rt_tables.h:
the static part of the tables of the run-time dense kernels
(src/mp_real/dense_rt.c), 64-bit limbs only.

The tables are floors at W = MP_REAL_DENSE_RT_W fraction limbs (at
least MP_REAL_DENSE_RT_MAX, the largest size of the kernels), of which
a kernel at n limbs reads the top n limbs (the floor at n limbs).  The
first two levels of every family are stored here: their arguments are
the largest (the first level's up to about 1, the second's up to about
2^-7), so they are the most expensive entries to compute at run time
(the Horner scheme of dense_rt.c wants a short argument below 2^-12).
The deeper levels are computed by the kernels as they are needed
(dense_rt.c).  The static per-size kernels (the
_mp_real_*_opt_<n> files of dev/gen_mp_real_dense_bodies.py) read their
first two levels from these tables too, and their deeper levels from
the ten-limb tables of dev/gen_mp_real_dense_tables.py, whose
definitions these follow:

  exp:   L_1[j] = s log 2 + log(1 + C_1[j] / 2^64)      j < 128
         G_2[j] = log(1 + j 2^-14)                      j <= 128
  log1p: M_1[j] = -log(1 - D_1[j])                      j < 128
         M_2[j] = -log(1 - D_2(j))                      j <= 128
  atan:  A_1[j] = atan(j / 2^7)                         j < 128
         A_2[j] = atan(j 2^-14)                         j <= 133
  sin, cos: T_1[j] = atan(C_1[j] / 2^64)                j < 64

with C_1, D_1 and the sin/cos C_1 the one-limb tables of dense_tables.c
(recomputed here from their definitions) and D_2(j) = c -
ceil(c^2 2^64) / 2^64, c = j 2^-14.

Run from the top-level FLINT directory:

    python3 dev/gen_mp_real_dense_rt_tables.py
"""

import mpmath
from mpmath import mp, mpf

W = 32              # MP_REAL_DENSE_RT_W (>= MP_REAL_DENSE_RT_MAX)
mp.prec = 64 * W + 192

B = 2 ** 64
BITS = 7

LICENSE = """/*
    Copyright (C) 2026 Fredrik Johansson

    This file is part of FLINT.

    FLINT is free software: you can redistribute it and/or modify it under
    the terms of the GNU Lesser General Public License (LGPL) as published
    by the Free Software Foundation; either version 3 of the License, or
    (at your option) any later version.  See <https://www.gnu.org/licenses/>.
*/"""

TABLES = []         # (name, comment, entries, data)


def limbs_of(x):
    """floor(x B^W) as W fraction limbs, x in [0, 1)"""
    v = int(mpmath.floor(x * mpf(B) ** W))
    assert v >= 0
    out = []
    for _ in range(W):
        out.append(v % B)
        v //= B
    assert v == 0, x
    return out


def table(name, comment, values):
    data = []
    for x in values:
        data.extend(limbs_of(x))
    TABLES.append((name, comment, len(values), data))


def exp_tables():
    s1 = min(j for j in range(128) if mpmath.exp(mpf(j) / 2 ** BITS) >= 2)
    l1 = []
    for j in range(128):
        sh = 1 if j >= s1 else 0
        c = int(mpmath.floor((mpmath.exp(mpf(j) / 2 ** BITS) / 2 ** sh - 1) * B))
        l1.append(sh * mpmath.log(2) + mpmath.log1p(mpf(c) / B))
    table("_mp_real_dense_rt_exp_l1",
          "L_1[j] = s log 2 + log(1 + C_1[j] / 2^64), j < 128", l1)
    table("_mp_real_dense_rt_exp_g2", "G_2[j] = log(1 + j 2^-14), j <= 128",
          [mpmath.log1p(mpf(j) / 2 ** (2 * BITS)) for j in range(129)])


def log_d(k, j):
    if k == 1:
        return mpf((B * j) // (2 ** BITS + j)) / B
    s = BITS * k
    num = -(-(j * j * B) // 2 ** (2 * s))
    return mpf(j) / 2 ** s - mpf(num) / B


def log_tables():
    table("_mp_real_dense_rt_log_m1", "M_1[j] = -log(1 - D_1[j]), j < 128",
          [-mpmath.log1p(-log_d(1, j)) for j in range(128)])
    table("_mp_real_dense_rt_log_m2", "M_2[j] = -log(1 - D_2(j)), j <= 128",
          [-mpmath.log1p(-log_d(2, j)) for j in range(129)])


def atan_tables():
    table("_mp_real_dense_rt_atan_a1", "A_1[j] = atan(j / 2^7), j < 128",
          [mpmath.atan(mpf(j) / 2 ** BITS) for j in range(128)])
    table("_mp_real_dense_rt_atan_a2", "A_2[j] = atan(j 2^-14), j <= 133",
          [mpmath.atan(mpf(j) / 2 ** (2 * BITS)) for j in range(134)])
    t1 = []
    for j in range(64):
        c = int(mpmath.floor(mpmath.tan(mpf(j) / 2 ** BITS) * B))
        t1.append(mpmath.atan(mpf(c) / B))
    table("_mp_real_dense_rt_sin_cos_t1",
          "T_1[j] = atan(C_1[j] / 2^64), sin/cos C_1, j < 64", t1)


def emit():
    c = open("src/mp_real/dense_rt_tables.c", "w")
    h = open("src/mp_real/dense_rt_tables.h", "w")
    hdr = "/* GENERATED by dev/gen_mp_real_dense_rt_tables.py -- do not edit */\n"
    total = sum(len(d) for _, _, _, d in TABLES) * 8
    c.write(LICENSE + "\n\n" + hdr + "\n")
    c.write('#include "flint.h"\n#include "dense_rt_tables.h"\n\n'
            '#if FLINT_BITS == 64\n\n')
    h.write(LICENSE + "\n\n" + hdr + "\n")
    h.write("#ifndef MP_REAL_DENSE_RT_TABLES_H\n"
            "#define MP_REAL_DENSE_RT_TABLES_H\n\n")
    h.write('#include "flint.h"\n\n#if FLINT_BITS == 64\n\n')
    h.write("/* the first two levels of the run-time dense kernels as floors\n"
            "   at MP_REAL_DENSE_RT_W fraction limbs (least significant\n"
            "   first); %d bytes in total */\n" % total)
    h.write("#define MP_REAL_DENSE_RT_W %d\n\n" % W)
    for name, comment, entries, data in TABLES:
        h.write("/* %s */\n" % comment)
        h.write("FLINT_DLL extern const ulong %s[%d];\n" % (name, len(data)))
        c.write("/* %s */\n" % comment)
        c.write("const ulong %s[%d] = {\n" % (name, len(data)))
        for i in range(0, len(data), W):
            row = data[i:i + W]
            for r in range(0, W, 3):
                c.write("    " + ", ".join("UWORD(0x%016x)" % d
                                           for d in row[r:r + 3]) + ",\n")
        c.write("};\n\n")
    c.write("#endif\n")
    h.write("\n#endif\n\n#endif\n")


if __name__ == "__main__":
    exp_tables()
    log_tables()
    atan_tables()
    emit()
