#!/usr/bin/env python3
"""Emit src/mp_real/dense_rt_series.inc: the log1p series of the
straight-line run-time dense kernels (src/mp_real/dense_rt.c), the hand
series of dev/gen_mp_real_dense_bodies.py (Horner in x with tapered
widths, no division) for x < 2^-63 at RT_LOG1P_SERIES_MIN ..
RT_LOG1P_SERIES_MAX limbs, where it beats 2 atanh(u / (2 + u)) by the
hardcoded atanh series and one division (measured: 1.33, 1.17, 1.10 and
1.05 times faster at 11, 12, 13 and 14 limbs; even at 15 and 16).

Run from the top-level FLINT directory:

    python3 dev/gen_mp_real_dense_rt_series.py > src/mp_real/dense_rt_series.inc
"""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))

NMIN, NMAX, R = 11, 14, 63


def main():
    spec = importlib.util.spec_from_file_location(
        "g_dense_body", os.path.join(HERE, "gen_mp_real_dense_bodies.py"))
    d = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(d)
    out = []
    o = out.append
    o("/* GENERATED by dev/gen_mp_real_dense_rt_series.py -- do not edit */")
    o("")
    o("#define RT_LOG1P_SERIES_MIN %d" % NMIN)
    o("#define RT_LOG1P_SERIES_MAX %d" % NMAX)
    o("")
    for n in range(NMIN, NMAX + 1):
        d.emit_log1p_series(o, n, R, "_rt_log1p_series_%d" % n)
    print("\n".join(out).rstrip("\n"))


if __name__ == "__main__":
    main()
