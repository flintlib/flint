#!/usr/bin/env python3
"""Emit src/mp_real/dense_rt_asm.inc: the rows of the straight-line
run-time dense kernels (src/mp_real/dense_rt.c) at RT_ASM_MIN ..
RT_ASM_MAX limbs as x86-64 inline assembly with mulx and the two
independent carry chains of adcx and adox, for builds with
FLINT_HAVE_ASSEMBLY_x86_64_adx (GNU C syntax).  One pass per row, four
or six instructions per limb; measured, a row costs about half of
mpn_mul_1 and mpn_add_n, or of the same rows in C.

With c one limb and P_i = floor(s c / B) limb i (the low product limb
dropped, so P is at most one ulp low), for n-limb s and d:

    _rt_asm_addmul_shift_<n>(d, s, c):  d += P, returning the carry out
    _rt_asm_submul_shift_<n>(d, s, c):  d -= P (no borrow out: d >= P),
                                        as ~(~d + P)
    _rt_asm_mul_shift_<n>(p, s, c):     p = P

d may equal s (every limb of s is read before the limb of d below it is
written).

Run from the top-level FLINT directory:

    python3 dev/gen_mp_real_dense_rt_asm.py > src/mp_real/dense_rt_asm.inc
"""

NMIN, NMAX = 11, 16


def q(s):
    return '        "%s\\n\\t"' % s


def gen(kind, n):
    L = []
    a = L.append
    a(q("xorl %k[z], %k[z]"))
    a(q("mulx 0(%[s]), %[l], %[h0]"))
    hs = ["h0", "h1"]
    for i in range(1, n + 1):
        hp = hs[(i - 1) % 2]
        if i < n:
            hc = hs[i % 2]
            a(q("mulx %d(%%[s]), %%[l], %%[%s]" % (8 * i, hc)))
            a(q("adcx %%[%s], %%[l]" % hp))
            v = "l"
        else:
            # the top limb of P: h_{n-1} + CF, below B
            a(q("adcx %%[z], %%[%s]" % hp))
            v = hp
        off = 8 * (i - 1)
        if kind == "add":
            a(q("adox %d(%%[d]), %%[%s]" % (off, v)))
            a(q("movq %%[%s], %d(%%[d])" % (v, off)))
        elif kind == "sub":
            a(q("movq %d(%%[d]), %%[t]" % off))
            a(q("notq %[t]"))
            a(q("adox %%[%s], %%[t]" % v))
            a(q("notq %[t]"))
            a(q("movq %%[t], %d(%%[d])" % off))
        else:
            a(q("movq %%[%s], %d(%%[d])" % (v, off)))
    if kind == "add":
        # the carry out: z = 0 + 0 + OF
        a(q("adox %[z], %[z]"))
    outs = ['[z] "=&r" (z)', '[l] "=&r" (l)', '[h0] "=&r" (h0)',
            '[h1] "=&r" (h1)']
    if kind == "sub":
        outs.append('[t] "=&r" (t)')
    name = {"add": "addmul", "sub": "submul", "mul": "mul"}[kind]
    rtype = "ulong" if kind == "add" else "void"
    out = []
    o = out.append
    o("FLINT_FORCE_INLINE %s" % rtype)
    o("_rt_asm_%s_shift_%d(nn_ptr d, nn_srcptr s, ulong c)" % (name, n))
    o("{")
    o("    ulong z, l, h0, h1%s;" % (", t" if kind == "sub" else ""))
    o("    __asm__ volatile(")
    out.extend(L)
    o("        : %s" % ", ".join(outs))
    o('        : [d] "r" (d), [s] "r" (s), "d" (c)')
    o('        : "cc", "memory");')
    if kind == "add":
        o("    return z;")
    o("}")
    o("")
    return out


def main():
    out = []
    o = out.append
    o("/* GENERATED by dev/gen_mp_real_dense_rt_asm.py -- do not edit */")
    o("")
    o("#define RT_ASM_MIN %d" % NMIN)
    o("#define RT_ASM_MAX %d" % NMAX)
    o("")
    for n in range(NMIN, NMAX + 1):
        for kind in ("add", "sub", "mul"):
            out.extend(gen(kind, n))
    for kind, name, rtype in (("add", "addmul", "ulong"),
                              ("sub", "submul", "void"),
                              ("mul", "mul", "void")):
        o("/* by a constant n in RT_ASM_MIN .. RT_ASM_MAX */")
        o("FLINT_FORCE_INLINE %s" % rtype)
        o("_rt_asm_%s_shift(nn_ptr d, nn_srcptr s, slong n, ulong c)" % name)
        o("{")
        o("    switch (n)")
        o("    {")
        for n in range(NMIN, NMAX):
            if rtype == "ulong":
                o("        case %d: return _rt_asm_%s_shift_%d(d, s, c);"
                  % (n, name, n))
            else:
                o("        case %d: _rt_asm_%s_shift_%d(d, s, c); return;"
                  % (n, name, n))
        if rtype == "ulong":
            o("        default: return _rt_asm_%s_shift_%d(d, s, c);"
              % (name, NMAX))
        else:
            o("        default: _rt_asm_%s_shift_%d(d, s, c); return;"
              % (name, NMAX))
        o("    }")
        o("}")
        o("")
    print("\n".join(out).rstrip("\n"))


if __name__ == "__main__":
    main()
